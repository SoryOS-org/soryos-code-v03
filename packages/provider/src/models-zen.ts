/** Modèles utilisables avec la clé publique (free tier). */
export const ZEN_FREE_MODELS: ZenModel[] = ZEN_MODELS.filter((m) => m.free);

/** Modèles payants (clé personnelle requise). */
export const ZEN_PAID_MODELS: ZenModel[] = ZEN_MODELS.filter((m) => !m.free);

/**
 * Modèle par défaut du provider : un modèle du FREE TIER, afin que le
 * provider fonctionne immédiatement avec la clé publique `public`
 * (sans clé, opencode n'expose que les modèles gratuits).
 */
export const ZEN_DEFAULT_MODEL: string =
  ZEN_FREE_MODELS.find((m) => m.supportsTools && m.contextTokens >= 200000)?.id ??
  ZEN_FREE_MODELS.find((m) => m.supportsTools)?.id ??
  ZEN_FREE_MODELS[0]?.id ??
  "big-pickle";

/** Un modèle est-il utilisable avec la clé donnée ? */
export function isZenModelUsable(modelId: string, apiKey: string | undefined | null): boolean {
  const model = ZEN_MODELS.find((m) => m.id === modelId);
  if (!model) return false;
  // Clé publique → uniquement les modèles gratuits.
  if (!apiKey || apiKey === "public") return model.free;
  return true;
}

